import java.util.Scanner;
class RelationalOperators{
    public static void main(String[] ars){
        Scanner sc = new Scanner(System.in);
        int k = sc.nextInt();
        int n = sc.nextInt();
        System.out.println(k==n);
        System.out.println(k!=n);
        System.out.println(k<n);
        System.out.println(k>n);
        System.out.println(k<=n);
        System.out.println(k>=n);
    }
}
